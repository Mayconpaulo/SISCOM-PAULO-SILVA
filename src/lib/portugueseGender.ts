/**
 * Infers "A" for female Brazilian Portuguese full names and "AO" for male names.
 */
export function inferPortugueseRecipientPrefix(fullName: string): 'AO' | 'A' {
  const firstToken = fullName
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toUpperCase()
    .replace(/[^A-Z\s]/g, ' ')
    .trim()
    .split(/\s+/)[0];

  if (!firstToken) return 'AO';
  if (MALE_FIRST_NAMES.has(firstToken)) return 'AO';
  if (FEMALE_FIRST_NAMES.has(firstToken)) return 'A';

  if (firstToken.length >= 3 && firstToken.endsWith('A')) {
    return 'A';
  }
  if (/(ELE|ELLE|ENE|ANE|IANE|LENE|ICE)$/.test(firstToken)) {
    return 'A';
  }

  return 'AO';
}

export function inferPortugueseContinuacaoArticle(
  fullName: string,
  override?: 'auto' | 'do' | 'da'
): 'do' | 'da' {
  if (override === 'do' || override === 'da') return override;
  return inferPortugueseRecipientPrefix(fullName) === 'A' ? 'da' : 'do';
}
